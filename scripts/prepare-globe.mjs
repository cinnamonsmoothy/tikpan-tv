import { readFile, writeFile } from 'node:fs/promises';

// Keep direct-file previews working without fetching JSON or tainting the canvas.
const root = new URL('../assets/globe/', import.meta.url);
const countries = JSON.parse(await readFile(new URL('countries.geojson', root), 'utf8'));
const earth = await readFile(new URL('earth.jpg', root));
const data = {
  earth: `data:image/jpeg;base64,${earth.toString('base64')}`,
  countries: {
    type: 'FeatureCollection',
    features: countries.features.filter(feature => feature.properties.CONTINENT === 'Africa')
      .map(feature => ({ type: 'Feature', properties: { CONTINENT: 'Africa' }, geometry: feature.geometry }))
  }
};
await writeFile(new URL('globe-data.js', root), `/* Earth texture and Africa geography for file:// and HTTP. Generated by scripts/prepare-globe.mjs. */\nwindow.TIKPAN_GLOBE_DATA = ${JSON.stringify(data)};\n`);
console.log(`Prepared globe data with ${data.countries.features.length} African countries.`);
